        mandates_qualified = any(q in job_text for q in ['cpa', 'chartered accountant', 'qualified accountant', 'aca', 'ca required'])
        is_eligible = True
        if mandates_qualified and not cand['is_qualified_ca']:
            is_eligible = False
            
        # 2. Skill Overlap
        matched_skills = cand_skills.intersection(job_skills)
        missing_skills = job_skills.difference(cand_skills)
        skill_ratio = len(matched_skills) / max(1, len(job_skills))
        
        # 3. Domain alignment
        domain_keywords = CA_TAXONOMY.get(cand['primary_domain'], [])
        domain_alignment = any(k in job_text for k in domain_keywords)
        
